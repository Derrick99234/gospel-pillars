// Read .env.local
const envFile = readFileSync(join(__dirname, '..', '.env.local'), 'utf-8');
const getVar = (name) => {
  const m = envFile.match(new RegExp('^' + name + '=(.*)$', 'm'));
  return m ? m[1].trim() : '';
};

