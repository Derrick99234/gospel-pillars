async function run() {
  console.log('🚀 Starting updates to Supabase...\n');

  // 1. Upsert Sections
  console.log(`📦 Upserting ${sectionsToUpsert.length} sections...`);
  const { error: secErr } = await supabase
    .from('sections')
    .upsert(sectionsToUpsert, { onConflict: 'id' });

  if (secErr) {
    console.error('❌ Failed to upsert sections:', secErr.message);
    process.exit(1);
  }
  console.log('   ✅ Sections upserted successfully!\n');

  // 2. Upsert Outlets
  console.log(`📦 Upserting ${outletsToUpsert.length} outlets...`);
  const batchSize = 50;
  for (let i = 0; i < outletsToUpsert.length; i += batchSize) {
    const batch = outletsToUpsert.slice(i, i + batchSize).map((o, idx) => ({
      ...o,
      index: i + idx + 1,
      updated_at: new Date().toISOString(),
    }));

    const { error: outErr } = await supabase
      .from('outlets')
      .upsert(batch, { onConflict: 'id' });

    if (outErr) {
      console.error(`❌ Failed on batch ${Math.floor(i / batchSize) + 1}:`, outErr.message);
      process.exit(1);
    }
    console.log(`   ✅ Batch ${Math.floor(i / batchSize) + 1}: ${batch.length} outlets upserted.`);
  }

  // 3. Move any remaining Nigeria outlets from old 'nigeria' section to their nearest division
  // e.g. Oyo, Osun, Ogun, Kwara, Ondo -> Central or Mainland/Western
  const { data: remainingNigeria } = await supabase
    .from('outlets')
    .select('id, name, address, state_or_province')
    .eq('section_id', 'nigeria');

  if (remainingNigeria && remainingNigeria.length > 0) {
    console.log(`\nℹ️ Found ${remainingNigeria.length} remaining outlets in old 'nigeria' section:`);
    for (const rem of remainingNigeria) {
      console.log(`   - ${rem.id}: ${rem.name}`);
    }
  }

  console.log('\n🎉 ALL UPDATES COMPLETE!');
}

run();
